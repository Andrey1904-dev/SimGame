namespace LifeFromZero.Economy.Core
{
    /// <summary>
    /// Абстракция кошелька игрока для экономического модуля.
    /// Реализуется адаптером поверх существующего MoneyWallet основного проекта.
    /// Модуль НЕ содержит собственной реализации кошелька и не хранит баланс.
    /// </summary>
    /// <remarks>
    /// Контракт, который обязан выполнить адаптер:
    /// <list type="bullet">
    /// <item><see cref="Balance"/> — чтение остатка без побочных эффектов и исключений.</item>
    /// <item><see cref="TrySpend"/> — списание атомарно: либо вся сумма, либо ничего.</item>
    /// <item><see cref="TryRefund"/> — возврат ровно той суммы, что была списана (компенсация).</item>
    /// </list>
    /// Все методы возвращают признак успеха; исключения адаптер должен преобразовывать
    /// в <c>false</c> (магазин дополнительно страхуется через <see cref="SafeCall"/>).
    /// </remarks>
    public interface IWalletAdapter
    {
        /// <summary>Текущий остаток. Неотрицательный.</summary>
        Money Balance { get; }

        /// <summary>
        /// Списывает <paramref name="amount"/> атомарно.
        /// </summary>
        /// <returns>
        /// <c>false</c>, если денег недостаточно или операция отклонена.
        /// При <c>false</c> баланс обязан остаться неизменным.
        /// </returns>
        bool TrySpend(Money amount);

        /// <summary>
        /// Возвращает ранее списанные деньги.
        /// Используется ТОЛЬКО для компенсации, когда после успешного списания
        /// операция не может быть завершена.
        /// </summary>
        /// <returns><c>false</c>, если начисление отклонено.</returns>
        bool TryRefund(Money amount);
    }

    /// <summary>
    /// Абстракция склада предметов игрока для экономического модуля.
    /// Реализуется адаптером поверх существующего FoodInventory основного проекта.
    /// Модуль НЕ содержит собственной реализации инвентаря и не знает правил сытости.
    /// </summary>
    /// <remarks>
    /// Контракт, который обязан выполнить адаптер:
    /// <list type="bullet">
    /// <item><see cref="CanApprove"/> — точная проверка, что инвентарь примет ровно
    /// <c>quantity</c> единиц. Без изменения состояния. Именно она позволяет не списывать
    /// деньги, когда места нет.</item>
    /// <item><see cref="TryAdd"/> — добавляет предметы; при <c>false</c> состояние
    /// обязано остаться неизменным (никаких частичных добавлений).</item>
    /// </list>
    /// Если существующий инвентарь не умеет проверять вместимость без мутации,
    /// правила проверки реализуются внутри адаптера — это единственное допустимое место
    /// для такой логики.
    /// </remarks>
    public interface IInventoryAdapter
    {
        /// <summary>
        /// Проверяет, что инвентарь сможет принять <paramref name="quantity"/> единиц
        /// предмета <paramref name="itemId"/>. Не изменяет состояние.
        /// </summary>
        bool CanApprove(string itemId, int quantity);

        /// <summary>
        /// Добавляет предметы. Вызывается магазином только после успешного
        /// <see cref="CanApprove"/> с тем же количеством.
        /// </summary>
        /// <returns>
        /// <c>false</c>, если добавление отклонено; в этом случае состояние не должно меняться,
        /// а магазин вернёт покупателю деньги.
        /// </returns>
        bool TryAdd(string itemId, int quantity);
    }
}
